package com.kve.common.kubejs;

import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Locale;

public final class KveScriptPaths {
    private KveScriptPaths() {}

    public static final Path STARTUP_ROOT = Paths.get("kubejs", "startup_scripts", "shovel_js");
    public static final Path SERVER_ROOT  = Paths.get("kubejs", "server_scripts", "shovel_js");
    public static final Path CLIENT_ROOT  = Paths.get("kubejs", "client_scripts", "shovel_js");
    /** Estado de los editores y configuracion propia de KVE (no scripts). */
    public static final Path CONFIG_ROOT  = Paths.get("kubejs", "config");

    public static Path recipesDir()                  { return SERVER_ROOT.resolve("recipes"); }
    public static Path recipeModDir(String modId)     { return recipesDir().resolve(sanitize(modId)); }
    public static Path recipeAddFile(String modId)    { return recipeModDir(modId).resolve("add.js"); }
    public static Path recipeRemoveFile(String modId) { return recipeModDir(modId).resolve("remove.js"); }

    public static Path blocksStartupDir()        { return STARTUP_ROOT.resolve("blocks"); }
    public static Path blockAttributesFile()     { return blocksStartupDir().resolve("attributes.js"); }
    public static Path blocksServerDir()         { return SERVER_ROOT.resolve("blocks"); }
    public static Path blockHarvestTagsFile()    { return blocksServerDir().resolve("harvest_tags.js"); }
    public static Path blockExactToolFile()      { return blocksServerDir().resolve("exact_tool.js"); }
    public static Path blockNetheriteTierFile()  { return blocksServerDir().resolve("netherite_tier.js"); }
    public static Path blockTooltipsFileClient() { return CLIENT_ROOT.resolve("blocks").resolve("tooltips.js"); }

    public static Path itemsStartupDir()           { return STARTUP_ROOT.resolve("items"); }
    public static Path itemAttributesFile()        { return itemsStartupDir().resolve("attributes.js"); }
    public static Path itemTooltipsFileClient()    { return CLIENT_ROOT.resolve("items").resolve("tooltips.js"); }
    public static Path itemHideViewersFileClient() { return CLIENT_ROOT.resolve("items").resolve("hide_viewers.js"); }

    public static Path mobsDir()  { return SERVER_ROOT.resolve("mobs"); }
    public static Path mobsFile() { return mobsDir().resolve("mobs.js"); }

    public static Path tagsDir()  { return SERVER_ROOT.resolve("tags"); }
    public static Path tagsFile() { return tagsDir().resolve("tags.js"); }

    public static Path tradesDir()  { return SERVER_ROOT.resolve("trades"); }
    public static Path tradesFile() { return tradesDir().resolve("trades.js"); }

    public static Path eventsDir()  { return SERVER_ROOT.resolve("events"); }
    public static Path eventsFile() { return eventsDir().resolve("events.js"); }
    /** Startup script puente para eventos Forge sin equivalente KubeJS (ver EventExporter#FORGE_BRIDGE_SCRIPT). */
    public static Path eventsForgeBridgeFile() { return STARTUP_ROOT.resolve("events").resolve("forge_bridge.js"); }

    public static Path packRulesServerFile()     { return SERVER_ROOT.resolve("pack").resolve("rules.js"); }
    public static Path packRulesInfoFileClient() { return CLIENT_ROOT.resolve("pack").resolve("recipe_viewer_info.js"); }
    /** kubejs/assets - KubeJS lo carga como resource pack por encima de los mods (nombres visibles). */
    public static final Path ASSETS_ROOT = Paths.get("kubejs", "assets");
    public static Path langFile(String namespace, String locale) {
        return ASSETS_ROOT.resolve(namespace).resolve("lang").resolve(locale + ".json");
    }

    public static void deleteLegacyLooseScripts() {
        for (Path root : new Path[]{SERVER_ROOT, STARTUP_ROOT, CLIENT_ROOT}) {
            if (!java.nio.file.Files.isDirectory(root)) continue;
            try (java.util.stream.Stream<Path> files = java.nio.file.Files.list(root)) {
                files.filter(f -> java.nio.file.Files.isRegularFile(f))
                     .filter(f -> {
                         String n = f.getFileName().toString();
                         return n.startsWith("shovel_js_") && n.endsWith(".js");
                     })
                     .filter(KveScriptPaths::isAutoGenerated)
                     .forEach(f -> {
                         try {
                             java.nio.file.Files.deleteIfExists(f);
                             if (f.startsWith(STARTUP_ROOT))
                                 com.kve.CraftEditorMod.LOGGER.warn("[Shovel JS] Startup script viejo eliminado: {} - ya se cargo en este arranque, REINICIA el juego para que deje de aplicarse", f);
                             else
                                 com.kve.CraftEditorMod.LOGGER.info("[Shovel JS] Script viejo duplicado eliminado: {}", f);
                         } catch (java.io.IOException ignored) {}
                     });
            } catch (java.io.IOException ignored) {}
        }
    }

    private static boolean isAutoGenerated(Path f) {
        try (java.io.BufferedReader r = java.nio.file.Files.newBufferedReader(f, java.nio.charset.StandardCharsets.UTF_8)) {
            for (int i = 0; i < 3; i++) {
                String line = r.readLine();
                if (line == null) return false;
                if (line.contains("AUTO-GENERATED") || line.contains("Auto-generado por Shovel JS")) return true;
            }
        } catch (Exception ignored) {}
        return false;
    }

    /** Nombre de carpeta seguro para un modid: minusculas, solo [a-z0-9_-]; sin mod / "minecraft" -> "vanilla". */
    public static String sanitize(String modId) {
        if (modId == null || modId.isBlank() || modId.equals("minecraft")) return "vanilla";
        String s = modId.toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9_-]", "_");
        return s.isBlank() ? "other" : s;
    }
}
